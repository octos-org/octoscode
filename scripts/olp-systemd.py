#!/usr/bin/env python3
"""OLP 保活:用 systemd 用户单元让单元上的常驻任务自动拉起(Linux)。

这是 olp-launchd.py 在 Linux 上的对应物,子命令与含义相同。多机部署时,每台
单元上有几件事必须一直在跑:向 hub 报心跳、转发负哨事件、终端工作区的后台
服务。本工具把它们注册成当前用户的 systemd 单元:开机后自动启动,退出后
自动重启。

子命令
  heartbeat --unit <单元号> --hub <ssh 目标> [--interval 60] [--scripts <目录>]
      注册心跳任务:每 --interval 秒执行一次
          olp-unit.py heartbeat --unit <单元号> | ssh <hub> receive
      hub 上这把密钥应配了强制命令(见 docs/OLP_CLUSTER.md),所以远端
      实际执行的是 `olp-unit.py receive --unit <单元号>`。
      单机部署写 --hub local:心跳直接交给本机的 `olp-unit.py receive`,不经 ssh。
  install <名字> (--interval 秒 | --keepalive) [--env K=V]... -- <命令> [参数…]
      注册任意命令。--interval 定时执行;--keepalive 常驻,退出即重启。
  uninstall <名字>
      停掉并删除一个任务。
  list
      列出本工具注册的任务,以及是否在运行。
  render <名字> (--interval 秒 | --keepalive) [--env K=V]... -- <命令> [参数…]
      只把单元文件打印到 stdout,不写文件。
  doctor
      检查这台机器是否适合常驻(当前用户开了 linger),只报告并给出修正
      命令,不修改任何设置。

  install / heartbeat / uninstall / list 都可加:
    --dir <目录>   单元文件所在目录(默认 ~/.config/systemd/user)
    --no-load      只写或删文件,不调用 systemctl

单元文件
  定时任务是一对文件:olp-<名字>.service(Type=oneshot)与 olp-<名字>.timer
  (开机 10 秒后第一次,之后每 --interval 秒一次)。常驻任务只有
  olp-<名字>.service(Restart=always,间隔 10 秒)。日志在
  ~/.octos/outer/logs/<名字>.log。systemd 给用户单元的 PATH 很短,所以默认
  写入 ~/.local/bin:~/.cargo/bin:/usr/local/bin:/usr/bin:/bin,可用 --env
  覆盖。

linger(必须)
  systemd 的用户单元默认只在该用户登录期间运行,最后一个会话结束就全部
  停掉。单元是无人值守的机器,必须给运行内环的用户打开 linger:
      sudo loginctl enable-linger <用户>
  之后用户单元在开机时启动,不需要任何人登录。doctor 检查这一项。

保活的边界(有意不做,与 olp-launchd.py 相同)
  - 只拉起基础设施。内环窗格里的对话、外环的主审权锁不会自动恢复:
    重启后由巡检上报,让大外环或人决定怎么接(协议 R7:活锁接管归
    operator)。
  - `octos serve` 在标准用法里是 TUI 的 stdio 子进程,随 TUI 启停,不单独
    注册成 systemd 单元。
  - 不改系统设置。doctor 给出的命令需要 sudo,由人执行。

退出码:0 成功;1 systemctl 失败或 doctor 发现问题;2 用法错误,或在非
Linux 上要求加载任务。
"""

import argparse
import getpass
import json
import os
import platform
import re
import shlex
import subprocess
import sys

PREFIX = "olp-"
MARKER = "# generated by scripts/olp-systemd.py; re-run the tool instead of editing"
COMMAND_MARK = "# olp-command: "
NAME_RE = re.compile(r"^[a-z0-9][a-z0-9-]{0,40}$")
UNIT_RE = re.compile(r"^[a-z][a-z0-9-]{0,31}$")
HUB_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._@-]{0,127}$")
ENV_KEY_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
RESTART_SEC = 10
FIRST_RUN_SEC = 10


class Fail(Exception):
    def __init__(self, code, msg):
        super().__init__(msg)
        self.code = code


def home():
    return os.path.expanduser("~")


def default_path():
    h = home()
    return f"{h}/.local/bin:{h}/.cargo/bin:/usr/local/bin:/usr/bin:/bin"


def units_dir(args):
    return args.dir or os.path.join(home(), ".config", "systemd", "user")


def log_path(name):
    return os.path.join(home(), ".octos", "outer", "logs", name + ".log")


def check_name(name):
    if not NAME_RE.match(name):
        raise Fail(2, f"名字不合法: {name}(小写字母、数字、连字符,以字母或数字开头)")
    return name


def quote_arg(arg):
    """One argument in systemd's ExecStart syntax.

    systemd splits on whitespace, honours double quotes with C-style escapes,
    and expands `%` specifiers and `$VAR`. Every argument is written quoted,
    with `\\`, `"` escaped and `%`, `$` doubled, so it reaches the program
    unchanged."""
    if "\n" in arg or "\r" in arg:
        raise Fail(2, "命令参数里不能有换行")
    out = arg.replace("\\", "\\\\").replace('"', '\\"').replace("%", "%%").replace("$", "$$")
    return f'"{out}"'


def quote_env(key, value):
    if "\n" in value or "\r" in value:
        raise Fail(2, f"--env {key} 的值里不能有换行")
    out = value.replace("\\", "\\\\").replace('"', '\\"').replace("%", "%%")
    return f'"{key}={out}"'


def build_units(name, command, interval, keepalive, env_pairs):
    """Returns {file name: text}: a service, plus a timer for interval jobs."""
    if not command:
        raise Fail(2, "缺少要运行的命令(写在 -- 之后)")
    if keepalive == (interval is not None):
        raise Fail(2, "--interval 与 --keepalive 必须且只能给一个")
    if interval is not None and not 10 <= interval <= 86400:
        raise Fail(2, "--interval 须在 10 到 86400 秒之间")
    if not os.path.isabs(command[0]):
        raise Fail(2, f"命令须写绝对路径(systemd 不按 PATH 找 ExecStart): {command[0]}")
    env = {"PATH": default_path()}
    for pair in env_pairs or []:
        key, sep, value = pair.partition("=")
        if not sep or not ENV_KEY_RE.match(key):
            raise Fail(2, f"--env 须写成 KEY=VALUE: {pair}")
        env[key] = value
    log = log_path(name)
    label = PREFIX + name
    lines = [
        MARKER,
        COMMAND_MARK + json.dumps(list(command), ensure_ascii=False),
        "[Unit]",
        f"Description=OctoLoop {name}",
        "",
        "[Service]",
    ]
    lines.append("Type=simple" if keepalive else "Type=oneshot")
    for key in sorted(env):
        lines.append("Environment=" + quote_env(key, env[key]))
    lines.append("ExecStart=" + " ".join(quote_arg(a) for a in command))
    lines.append(f"StandardOutput=append:{log}")
    lines.append(f"StandardError=append:{log}")
    if keepalive:
        lines += ["Restart=always", f"RestartSec={RESTART_SEC}", "", "[Install]", "WantedBy=default.target"]
    units = {label + ".service": "\n".join(lines) + "\n"}
    if not keepalive:
        units[label + ".timer"] = "\n".join(
            [
                MARKER,
                "[Unit]",
                f"Description=OctoLoop {name} (every {interval} s)",
                "",
                "[Timer]",
                f"OnBootSec={FIRST_RUN_SEC}",
                f"OnActiveSec={FIRST_RUN_SEC}",
                f"OnUnitActiveSec={interval}",
                "AccuracySec=1",
                f"Unit={label}.service",
                "",
                "[Install]",
                "WantedBy=timers.target",
            ]
        ) + "\n"
    return units


def enable_target(units):
    """The unit to enable: the timer of an interval job, else the service."""
    timers = [n for n in units if n.endswith(".timer")]
    return timers[0] if timers else next(iter(units))


def systemctl(*args):
    # `systemctl --user` finds the user manager through XDG_RUNTIME_DIR. A
    # shell reached by su, sudo -u or a bare ssh command often lacks it even
    # though the manager is running (linger); point at the standard place.
    env = dict(os.environ)
    env.setdefault("XDG_RUNTIME_DIR", f"/run/user/{os.getuid()}")
    return subprocess.run(["systemctl", "--user", *args], capture_output=True, text=True, env=env)


def stop_job(label):
    """Stop and disable both units of a job. One call per unit: systemctl
    fails the whole command when any named unit does not exist, and a job has
    a timer only in interval mode — a combined call would leave the service
    of a keepalive job running."""
    for ext in (".timer", ".service"):
        systemctl("disable", "--now", label + ext)
    systemctl("reset-failed", label + ".service")


def require_linux_for_load(args):
    if args.no_load:
        return
    if platform.system() != "Linux":
        raise Fail(2, "systemd 只在 Linux 上可用;在别的系统上只能加 --no-load 写文件")


def write_and_load(args, name, units):
    require_linux_for_load(args)
    directory = units_dir(args)
    os.makedirs(directory, exist_ok=True)
    os.makedirs(os.path.dirname(log_path(name)), exist_ok=True)
    label = PREFIX + name
    # An interval job that becomes a keepalive job must not leave its timer.
    stale = [label + ext for ext in (".service", ".timer") if label + ext not in units]
    if not args.no_load:
        # 已在运行的同名任务先停掉,新的配置才会生效;没在运行时失败是正常的。
        stop_job(label)
    for fname in stale:
        path = os.path.join(directory, fname)
        if os.path.isfile(path):
            os.unlink(path)
    for fname, text in units.items():
        path = os.path.join(directory, fname)
        tmp = path + ".tmp"
        with open(tmp, "w", encoding="utf-8") as f:
            f.write(text)
        os.chmod(tmp, 0o644)
        os.replace(tmp, path)
        print(f"written {path}")
    if args.no_load:
        return 0
    r = systemctl("daemon-reload")
    if r.returncode != 0:
        detail = r.stderr.strip() or r.stdout.strip()
        hint = ""
        if "connect to bus" in detail:
            # No user manager: nobody is logged in and linger is off.
            hint = (
                f"。这个用户的 systemd 没有在运行:先执行 sudo loginctl enable-linger {getpass.getuser()}"
                ",再重跑本命令(单元文件已写好)"
            )
        raise Fail(1, f"systemctl --user daemon-reload 失败: {detail}{hint}")
    target = enable_target(units)
    r = systemctl("enable", "--now", target)
    if r.returncode != 0:
        raise Fail(1, f"systemctl --user enable --now {target} 失败: {r.stderr.strip() or r.stdout.strip()}")
    print(f"enabled {target}")
    return 0


def cmd_render(args):
    units = build_units(check_name(args.name), args.command, args.interval, args.keepalive, args.env)
    for fname, text in units.items():
        sys.stdout.write(f"# --- {fname}\n{text}")
    return 0


def cmd_install(args):
    name = check_name(args.name)
    units = build_units(name, args.command, args.interval, args.keepalive, args.env)
    return write_and_load(args, name, units)


def cmd_heartbeat(args):
    if not UNIT_RE.match(args.unit):
        raise Fail(2, f"单元号不合法: {args.unit}")
    if not HUB_RE.match(args.hub):
        raise Fail(2, f"--hub 不是合法的 ssh 目标: {args.hub}")
    scripts = os.path.abspath(args.scripts or os.path.dirname(os.path.abspath(__file__)))
    tool = os.path.join(scripts, "olp-unit.py")
    if not os.path.isfile(tool):
        print(f"olp-systemd: 提醒:{tool} 现在不存在,任务运行时需要它", file=sys.stderr)
    pipeline = (
        f"python3 -B {shlex.quote(tool)} heartbeat --unit {shlex.quote(args.unit)}"
        f" | ssh -o BatchMode=yes -o ConnectTimeout=10 {shlex.quote(args.hub)} receive"
    )
    if args.hub == "local":
        # Single machine: hand the heartbeat to the hub side directly.
        pipeline = (
            f"python3 -B {shlex.quote(tool)} heartbeat --unit {shlex.quote(args.unit)}"
            f" | python3 -B {shlex.quote(tool)} receive --unit {shlex.quote(args.unit)}"
        )
    units = build_units("heartbeat", ["/bin/sh", "-c", pipeline], args.interval, False, args.env)
    return write_and_load(args, "heartbeat", units)


def cmd_uninstall(args):
    name = check_name(args.name)
    require_linux_for_load(args)
    label = PREFIX + name
    directory = units_dir(args)
    if not args.no_load:
        stop_job(label)
    removed = False
    for ext in (".timer", ".service"):
        path = os.path.join(directory, label + ext)
        if os.path.isfile(path):
            os.unlink(path)
            print(f"removed {path}")
            removed = True
    if not removed:
        print(f"{os.path.join(directory, label + '.service')} 不存在")
    if not args.no_load:
        systemctl("daemon-reload")
    return 0


def read_unit(path):
    """(is ours, command list or None, {key: value} of the last section seen per key)."""
    try:
        with open(path, "r", encoding="utf-8") as f:
            text = f.read()
    except OSError:
        return False, None, {}
    ours = MARKER in text
    command = None
    values = {}
    for line in text.splitlines():
        if line.startswith(COMMAND_MARK):
            try:
                command = json.loads(line[len(COMMAND_MARK):])
            except ValueError:
                command = None
        elif "=" in line and not line.startswith("#"):
            key, _, value = line.partition("=")
            values[key.strip()] = value.strip()
    return ours, command, values


def cmd_list(args):
    directory = units_dir(args)
    names = []
    if os.path.isdir(directory):
        for entry in sorted(os.listdir(directory)):
            if entry.startswith(PREFIX) and entry.endswith(".service"):
                if read_unit(os.path.join(directory, entry))[0]:
                    names.append(entry[len(PREFIX):-len(".service")])
    if not names:
        print("没有本工具注册的任务")
        return 0
    can_ask = not args.no_load and platform.system() == "Linux"
    for name in names:
        label = PREFIX + name
        _, command, _ = read_unit(os.path.join(directory, label + ".service"))
        timer = os.path.join(directory, label + ".timer")
        if os.path.isfile(timer):
            mode = f"每 {read_unit(timer)[2].get('OnUnitActiveSec', '?')} 秒"
            target = label + ".timer"
        else:
            mode = "常驻"
            target = label + ".service"
        if can_ask:
            active = systemctl("is-active", target).stdout.strip()
            state = "运行中" if active == "active" else f"未运行({active or 'unknown'})"
        else:
            state = "未查询"
        shown = " ".join(command) if command else "(命令不可读)"
        print(f"{name}\t{mode}\t{state}\t{shown}")
    return 0


def parse_linger(text):
    """`loginctl show-user` prints `Linger=yes`; `--value` prints just `yes`."""
    for line in text.splitlines():
        stripped = line.strip()
        if stripped.startswith("Linger="):
            return stripped[len("Linger="):]
        if stripped in ("yes", "no"):
            return stripped
    return None


def cmd_doctor(args):
    user = getpass.getuser()
    if args.linger_output:
        with open(args.linger_output, "r", encoding="utf-8") as f:
            text = f.read()
    else:
        if platform.system() != "Linux":
            raise Fail(2, "doctor 检查的是 systemd 的 linger;在别的系统上不适用")
        try:
            r = subprocess.run(
                ["loginctl", "show-user", user, "--property=Linger"], capture_output=True, text=True
            )
        except FileNotFoundError:
            raise Fail(1, "找不到 loginctl:这台机器不是 systemd 系统,本工具不适用")
        # A user with no session and no linger is unknown to logind.
        text = r.stdout if r.returncode == 0 else "Linger=no\n"
    fix = f"sudo loginctl enable-linger {user}"
    got = parse_linger(text)
    problems = 0
    if got == "yes":
        print(f"ok    用户单元在开机时启动,不需要登录(Linger = yes,用户 {user})")
    elif got == "no":
        problems += 1
        print(f"FAIL  用户单元只在 {user} 登录期间运行:Linger = no。修正:{fix}")
    else:
        problems += 1
        print(f"??    读不到 {user} 的 Linger 设置。修正:{fix}")
    print("提醒  桌面发行版可能自动休眠:单元要关掉(sudo systemctl mask sleep.target suspend.target)。")
    return 1 if problems else 0


def add_job_flags(p):
    p.add_argument("--interval", type=int)
    p.add_argument("--keepalive", action="store_true")
    p.add_argument("--env", action="append")


def add_dir_flags(p):
    p.add_argument("--dir")
    p.add_argument("--no-load", action="store_true")


def main():
    ap = argparse.ArgumentParser(prog="olp-systemd.py", add_help=True)
    sub = ap.add_subparsers(dest="cmd", required=True)

    p = sub.add_parser("render")
    p.add_argument("name")
    add_job_flags(p)

    p = sub.add_parser("install")
    p.add_argument("name")
    add_job_flags(p)
    add_dir_flags(p)

    p = sub.add_parser("heartbeat")
    p.add_argument("--unit", required=True)
    p.add_argument("--hub", required=True)
    p.add_argument("--interval", type=int, default=60)
    p.add_argument("--scripts")
    p.add_argument("--env", action="append")
    add_dir_flags(p)

    p = sub.add_parser("uninstall")
    p.add_argument("name")
    add_dir_flags(p)

    p = sub.add_parser("list")
    add_dir_flags(p)

    p = sub.add_parser("doctor")
    p.add_argument("--linger-output", help="读这个文件而不是运行 loginctl(测试与离线检查用)")

    # The job's own command follows `--`; split it off before argparse so its
    # flags are never mistaken for ours.
    argv = sys.argv[1:]
    command = []
    if "--" in argv:
        cut = argv.index("--")
        argv, command = argv[:cut], argv[cut + 1:]
    try:
        args = ap.parse_args(argv)
    except SystemExit as exc:
        return 2 if exc.code not in (0, None) else 0
    if args.cmd in ("install", "render"):
        args.command = command
    elif command:
        print(f"olp-systemd: {args.cmd} 不接受 -- 之后的命令", file=sys.stderr)
        return 2
    handlers = {
        "render": cmd_render,
        "install": cmd_install,
        "heartbeat": cmd_heartbeat,
        "uninstall": cmd_uninstall,
        "list": cmd_list,
        "doctor": cmd_doctor,
    }
    try:
        return handlers[args.cmd](args)
    except Fail as e:
        print(f"olp-systemd: {e}", file=sys.stderr)
        return e.code


if __name__ == "__main__":
    sys.exit(main())
