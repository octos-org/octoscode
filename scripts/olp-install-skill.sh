#!/usr/bin/env bash
# 安装 /octoloop 的全局入口:让任何项目里的 agent 都能用 OctoLoop 的规程。
#
# 规程正文只有一份:本仓库的 skills/octoloop/AGENTS.md(纯 Markdown,对所有
# agent 通用)。本脚本不复制正文,只做两件事:
#   1. 记下本仓库在哪:写 ~/.octos/outer/octoscode-home(一行路径)。
#   2. 装一张"薄卡":它不含任何固定路径,只告诉 agent 怎么找到本仓库、
#      然后去读正文。正文随 `git pull` 更新,薄卡不用重装。
#
# 用法:
#   scripts/olp-install-skill.sh                 # 装给 Claude Code:~/.claude/skills/octoloop/SKILL.md
#   scripts/olp-install-skill.sh --to <文件>     # 把薄卡写到别的 agent 读取的位置
#   scripts/olp-install-skill.sh --print         # 只把薄卡打印到 stdout,不写任何文件
#   scripts/olp-install-skill.sh --home-only     # 只记录仓库位置,不装薄卡
#   选项 --force:目标已存在且不是本脚本生成的时,先备份为 <文件>.bak 再覆盖
#
# 仓库搬家之后:在新位置重跑本脚本(只更新那一行路径);或者设置环境变量
# OCTOSCODE_HOME,它的优先级最高。
#
# 退出码:0 成功;2 用法错误;3 目标已存在且不是本脚本生成的(未加 --force)。
set -euo pipefail

die() { echo "olp-install-skill: $*" >&2; exit 2; }

MODE=claude
TARGET=""
FORCE=0
while [ $# -gt 0 ]; do
    case "$1" in
        --to)
            [ $# -ge 2 ] || die "--to 需要一个文件路径"
            MODE=file
            TARGET=$2
            shift 2
            ;;
        --print) MODE=print; shift ;;
        --home-only) MODE=home; shift ;;
        --force) FORCE=1; shift ;;
        -h | --help) sed -n '2,21p' "$0"; exit 0 ;;
        *) die "未知参数: $1" ;;
    esac
done

REPO=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd -P)
BODY="$REPO/skills/octoloop/AGENTS.md"
[ -f "$BODY" ] || die "找不到规程正文: $BODY"
DESCRIPTION=$(sed -n 's/^description:[[:space:]]*//p' "$BODY" | head -n 1)
[ -n "$DESCRIPTION" ] || die "规程正文缺少 description 行: $BODY"

MARKER='<!-- generated by scripts/olp-install-skill.sh; do not edit, re-run the script -->'

# 薄卡里没有任何固定路径:找仓库的办法写成规则,由 agent 在运行时解析。
render() {
    cat <<EOF
---
name: octoloop
description: ${DESCRIPTION}。任意项目可用。
---
$MARKER

# /octoloop(全局入口)

本卡是薄封装,不含规程正文,也不含固定路径。正文对所有 agent 通用,始终以
octoscode 仓库里的最新版为准。

## 第一步:找到 octoscode 仓库(OCTOSCODE_HOME)

按顺序取第一个**含 \`skills/octoloop/AGENTS.md\`** 的目录:

1. 环境变量 \`OCTOSCODE_HOME\`;
2. 文件 \`~/.octos/outer/octoscode-home\` 的内容(安装时记录的仓库位置);
3. 当前项目的根目录(当前项目就是 octoscode 时)。

一条命令完成解析(输出仓库路径;找不到时无输出、退出码非 0):

\`\`\`bash
for h in "\${OCTOSCODE_HOME:-}" "\$(cat ~/.octos/outer/octoscode-home 2>/dev/null)" "\$(git rev-parse --show-toplevel 2>/dev/null)"; do [ -n "\$h" ] && [ -f "\$h/skills/octoloop/AGENTS.md" ] && { echo "\$h"; break; }; done | grep .
\`\`\`

三处都找不到:**停下告诉用户**,不要猜路径、不要凭记忆操作。让用户克隆
octoscode 仓库后在其中执行 \`scripts/olp-install-skill.sh\`,或设置
\`OCTOSCODE_HOME\`。

## 第二步:加载规程正文

完整读取 \`\$OCTOSCODE_HOME/skills/octoloop/AGENTS.md\`,按其中规程执行。

## 路径解析规则(贯穿全程)

| 正文写法 | 解析到 |
|---|---|
| \`docs/…\`、\`knowledge/…\` 等规程文档 | \`\$OCTOSCODE_HOME/…\` |
| \`scripts/olp-*\` | \`\$OCTOSCODE_HOME/scripts/…\`(脚本自带定位,可从任意目录调用) |
| \`.octos/…\`(黑板、loop.md、信箱) | **当前项目**根目录 |
| 脚本参数 \`<repo>\`、\`<板>\` | **当前项目**(用绝对路径) |

当前项目就是 octoscode 本身时,一切相对路径直接按当前目录解析。

## 保持最新

正文随 \`git -C "\$OCTOSCODE_HOME" pull\` 更新,本卡不用重装。执行 init 或
outer 前,若 \`git -C "\$OCTOSCODE_HOME" status -sb\` 显示落后于 origin,先问
用户是否拉取。仓库搬家后,在新位置重跑 \`scripts/olp-install-skill.sh\`。
EOF
}

if [ "$MODE" = print ]; then
    render
    exit 0
fi

# 1. 记录仓库位置(唯一存放路径的地方,一行,随时可改)。
# 经 `octoscode olp skill install` 运行时,这里是某个版本的工具目录
# (olp-bundle/<哈希>);记它旁边的 current 链接,它总指向最近运行的版本。
CURRENT="$(dirname "$REPO")/current"
if [ -n "${OCTOSCODE_BIN:-}" ] && [ -L "$CURRENT" ] &&
    [ "$(cd "$CURRENT" 2>/dev/null && pwd -P)" = "$REPO" ]; then
    REPO="$CURRENT"
fi
HOME_FILE="$HOME/.octos/outer/octoscode-home"
mkdir -p "$(dirname "$HOME_FILE")"
printf '%s\n' "$REPO" > "$HOME_FILE"
echo "recorded octoscode home: $REPO  ($HOME_FILE)"
[ "$MODE" = home ] && exit 0

# 2. 装薄卡。
[ "$MODE" = claude ] && TARGET="$HOME/.claude/skills/octoloop/SKILL.md"
if [ -e "$TARGET" ] && ! grep -qF "$MARKER" "$TARGET"; then
    if [ "$FORCE" -ne 1 ]; then
        echo "olp-install-skill: $TARGET 已存在,而且不是本脚本生成的。" >&2
        echo "  看过它的内容后,加 --force 覆盖(原文件会备份为 $TARGET.bak)。" >&2
        exit 3
    fi
    cp "$TARGET" "$TARGET.bak"
    echo "backed up the existing file to $TARGET.bak"
fi
mkdir -p "$(dirname "$TARGET")"
TMP=$(mktemp "$(dirname "$TARGET")/.olp-skill.XXXXXX")
render > "$TMP"
chmod 644 "$TMP"
mv "$TMP" "$TARGET"
echo "installed: $TARGET"
